// Rebuilds extension/vendor/carta-assets/carta-assets.js from the two
// letterhead SVGs of the pns.zonas notification letter
// (docs/carta_notificacao_assets/ibge_logo.svg and brasao.svg in that
// repository — not vendored here; pass the directory as the argument)
// and the envelope background, the full-page A4 JPEG of the IBGE
// "Modelo de envelope" (passed as the second argument, embedded as is).
// Rasterizes with @resvg/resvg-js (dev-only; `bun add @resvg/resvg-js`
// in a scratch directory and run with `bun scripts/gen-carta-assets.mjs
// <assets-dir> <envelope.jpeg>`), then base64-embeds the PNGs into one MAIN-world script
// that sets a single global. The extension never fetches these: the
// script is a web-accessible vendored resource, loaded on first use.
import { Resvg } from '@resvg/resvg-js';
import { readFileSync, writeFileSync } from 'fs';
import { join } from 'path';

const [dir, envelopePath] = process.argv.slice(2);
if (!dir || !envelopePath) {
  throw new Error('usage: bun scripts/gen-carta-assets.mjs <dir with ibge_logo.svg and brasao.svg> <envelope.jpeg>');
}

function png(name, width) {
  const svg = readFileSync(join(dir, name), 'utf8')
    .replace(/^<svg width="[^"]*" height="[^"]*"/, '<svg');
  const r = new Resvg(svg, { fitTo: { mode: 'width', value: width } });
  return Buffer.from(r.render().asPng()).toString('base64');
}

// Logo ~1400 px wide (rendered 6.2 cm), brasão 512 px (rendered 1.9 cm high).
const logo = png('ibge_logo.svg', 1400);
const brasao = png('brasao.svg', 512);
const envelope = readFileSync(envelopePath).toString('base64');

const out = `// SIGC-PRO: images for the Carta de notificação, base64: the two
// letterhead PNGs and the envelope page's background JPEG. GENERATED by scripts/gen-carta-assets.mjs — do not edit by hand.
// Sources: the IBGE logo with wordmark and the Brasão da República, from
// the pns.zonas letter's SVGs; the IBGE envelope model. One global, nothing else: loaded on first
// use through the same relay/.jsUrl pattern as the Leaflet bundle.
(function () {
  'use strict';
  window.__sigcProCartaAssets = {
    logoPng: '${logo}',
    brasaoPng: '${brasao}',
    envelopeJpg: '${envelope}',
  };
})();
`;
writeFileSync(new URL('../extension/vendor/carta-assets/carta-assets.js', import.meta.url), out);
console.log('logo', logo.length, 'brasao', brasao.length, 'envelope', envelope.length);
